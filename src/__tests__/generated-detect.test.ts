// Per `architecture/v1-launch-plan.md` Step 4: detect machine-
// generated source files via filename pattern, generated dir,
// codegen toolchain marker, header comment, or binary blob.
//
// The reason set is pinned by the canonical-set test below so
// any drift fires here. §0.6.2 in action — the engine
// `GENERATED_REASONS` array and `FILTER_REASONS` in
// `extraction-stats.ts` MUST agree.

import { describe, it } from "node:test";
import assert from "node:assert/strict";
import {
  isGeneratedFile,
  GENERATED_REASONS,
  isBinaryContent,
} from "../extractors/generated-detect.ts";
import { FILTER_REASONS } from "../domain/extraction-stats.ts";

describe("generated-detect: canonical reason set", () => {
  it("GENERATED_REASONS has 5 entries", () => {
    assert.equal(GENERATED_REASONS.length, 5);
  });

  it("every GENERATED_REASONS member is in FILTER_REASONS", () => {
    for (const r of GENERATED_REASONS) {
      assert.ok(
        FILTER_REASONS.includes(r as (typeof FILTER_REASONS)[number]),
        `${r} missing from FILTER_REASONS`,
      );
    }
  });
});

describe("generated-detect: filename patterns (existing surface)", () => {
  const cases: { path: string; expected: boolean }[] = [
    { path: "/r/api.pb.go", expected: true },
    { path: "/r/types.pb.ts", expected: true },
    { path: "/r/proto_pb2.py", expected: true },
    { path: "/r/proto_pb2_grpc.py", expected: true },
    { path: "/r/zz_generated_deepcopy.go", expected: true },
    { path: "/r/foo_string.go", expected: true },
    { path: "/r/schema.generated.ts", expected: true },
    { path: "/r/user.g.dart", expected: true },
    { path: "/r/user.freezed.dart", expected: true },
    { path: "/r/src/app.ts", expected: false },
    { path: "/r/lib/util.go", expected: false },
  ];
  for (const c of cases) {
    it(`${c.expected ? "DETECTS" : "skips"} ${c.path}`, () => {
      assert.equal(isGeneratedFile(c.path).isGenerated, c.expected);
    });
  }
});

describe("generated-detect: generated directory", () => {
  it("flags files inside __generated__/", () => {
    const r = isGeneratedFile("/r/app/__generated__/types.ts");
    assert.equal(r.isGenerated, true);
    assert.equal(r.reason, "generated-directory");
  });
  it("flags files inside .generated/", () => {
    const r = isGeneratedFile("/r/.generated/foo.ts");
    assert.equal(r.isGenerated, true);
    assert.equal(r.reason, "generated-directory");
  });
});

describe("generated-detect: 8 codegen toolchains per Step 4", () => {
  const cases: { path: string; toolchain: string; sourceFile?: string }[] = [
    // 1. protoc — Java + C++ + Ruby + Rust
    { path: "/r/api/UserOuterClass.java", toolchain: "protoc" },
    { path: "/r/api/user.pb.cc", toolchain: "protoc" },
    { path: "/r/api/user.pb.h", toolchain: "protoc" },
    { path: "/r/api/user_pb.rb", toolchain: "protoc" },
    { path: "/r/api/user.pb.rs", toolchain: "protoc" },
    // 2. swagger-codegen
    { path: "/r/swagger-client/api.ts", toolchain: "swagger-codegen" },
    { path: "/r/lib/SwaggerClient.ts", toolchain: "swagger-codegen" },
    // 3. openapi-generator
    { path: "/r/generated-sources/openapi/Api.java", toolchain: "openapi-generator" },
    { path: "/r/openapi/generated/client.ts", toolchain: "openapi-generator" },
    { path: "/r/api.openapi.gen.ts", toolchain: "openapi-generator" },
    // 4. prisma
    { path: "/r/node_modules/.prisma/client/index.d.ts", toolchain: "prisma" },
    { path: "/r/lib/@prisma/client/index.js", toolchain: "prisma" },
    { path: "/r/prisma/migrations/20240101_init/migration.sql", toolchain: "prisma" },
    // 5. sqlc — also gives us a sourceFile
    { path: "/r/db/queries.sql.go", toolchain: "sqlc", sourceFile: "/r/db/queries.sql" },
    // 6. sqlboiler
    { path: "/r/models/boil_main.go", toolchain: "sqlboiler" },
    { path: "/r/models/user.boilerplate.go", toolchain: "sqlboiler" },
    // 7. datamodel-code-generator
    { path: "/r/app/pydantic_models/user.py", toolchain: "datamodel-code-generator" },
    // 8. oapi-codegen
    { path: "/r/internal/api/server.gen.go", toolchain: "oapi-codegen" },
  ];

  for (const c of cases) {
    it(`detects ${c.toolchain}: ${c.path}`, () => {
      const r = isGeneratedFile(c.path);
      assert.equal(r.isGenerated, true);
      assert.equal(r.reason, "codegen-toolchain");
      assert.equal(r.detail, c.toolchain);
      if (c.sourceFile) {
        assert.equal(r.sourceFile, c.sourceFile);
      }
    });
  }
});

describe("generated-detect: 10 first-line markers", () => {
  const HEADERS: { name: string; content: string }[] = [
    { name: "go-generate", content: "// Code generated by protoc. DO NOT EDIT.\npackage foo\n" },
    { name: "python-generator", content: "# Generated by datamodel-codegen\nimport pydantic\n" },
    { name: "generic AUTO-GENERATED", content: "// AUTO-GENERATED FILE\nconst x = 1;\n" },
    { name: "TS this-file-is-generated", content: "// This file is generated\nexport const x = 1;\n" },
    { name: "ts-codegen", content: "/* eslint-disable */\n// @generated\nexport const x = 1;\n" },
    { name: "graphql-codegen", content: "/* @generated\n * by graphql-codegen\n */\nexport const Query = {};\n" },
    { name: "hash DO NOT EDIT", content: "# DO NOT EDIT THIS FILE\nimport os\n" },
    { name: "dart-build_runner", content: "// GENERATED CODE - DO NOT MODIFY BY HAND\nimport 'foo.dart';\n" },
    { name: "sql-codegen", content: "-- Code generated by sqlc. DO NOT EDIT.\nSELECT * FROM users;\n" },
    { name: "java-codegen", content: "<!-- Generated by JAXB -->\n<elements>\n</elements>\n" },
  ];

  for (const h of HEADERS) {
    it(`detects header: ${h.name}`, () => {
      const r = isGeneratedFile("/r/src/some-file.ts", h.content);
      assert.equal(r.isGenerated, true);
      assert.equal(r.reason, "header-comment");
    });
  }

  it("does NOT flag plain authored source as generated", () => {
    const r = isGeneratedFile("/r/src/app.ts", "// Hand-written application code\nexport function main() {}\n");
    assert.equal(r.isGenerated, false);
  });
});

describe("generated-detect: binary blob detection", () => {
  it("flags content with a NUL byte in the first KB", () => {
    const content = "JPEG\u0000\u0000\u0000\u0000binary data";
    const r = isGeneratedFile("/r/assets/img.bin", content);
    assert.equal(r.isGenerated, true);
    assert.equal(r.reason, "binary-blob");
  });

  it("does NOT flag plain text without NUL bytes", () => {
    const content = "Hello world\nThis is just text.\n";
    const r = isGeneratedFile("/r/README.md", content);
    assert.equal(r.isGenerated, false);
  });

  it("flags high non-printable density (image / compiled blob)", () => {
    // Simulate a binary header with mostly control bytes.
    const bytes = new Array(200).fill(0).map((_, i) => String.fromCharCode(i % 6 + 1)).join("");
    assert.equal(isBinaryContent(bytes), true);
  });

  it("isBinaryContent returns false for plain UTF-8 prose", () => {
    assert.equal(isBinaryContent("Hello, world! This is just prose."), false);
  });
});

describe("generated-detect: precedence — filename wins over header", () => {
  it("a `.pb.go` file is filename-pattern even if it has no header", () => {
    const r = isGeneratedFile("/r/api/user.pb.go");
    assert.equal(r.isGenerated, true);
    assert.equal(r.reason, "filename-pattern");
    assert.equal(r.sourceFile, "/r/api/user.proto");
  });
});
