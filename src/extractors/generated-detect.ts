// Per `architecture/v1-launch-plan.md` Step 4 + doc-25 §2.1: detect
// machine-generated source so Schema's graph reflects authored
// code, not vendored or codegen output. The detector returns a
// discriminated result with the specific reason (filename pattern,
// generated-directory, header comment, codegen-toolchain marker,
// or binary blob) so `caching.stats` can break filter rates down
// per category.
//
// Step 4 expands the original 11-pattern surface to cover the 8
// codegen toolchains called out by the plan:
//   protoc, swagger-codegen, openapi-generator, prisma, sqlc,
//   sqlboiler, datamodel-code-generator, oapi-codegen.
// Plus 10 first-line markers and binary-blob detection.

/** Categories surfaced by the detector. Each contributes a
 *  distinct line in the `caching.stats` filter breakdown so a
 *  user can see "23 files filtered: 5 generated, 12 protobuf,
 *  6 binary." Per §0.6.2 — single source of truth for the
 *  client (`clients/studio/src/lib/...` will mirror this set
 *  when the banner is wired up). */
export type GeneratedReason =
  | "filename-pattern"
  | "generated-directory"
  | "header-comment"
  | "codegen-toolchain"
  | "binary-blob";

export const GENERATED_REASONS: readonly GeneratedReason[] = [
  "filename-pattern",
  "generated-directory",
  "header-comment",
  "codegen-toolchain",
  "binary-blob",
];

export interface GeneratedFileInfo {
  readonly isGenerated: boolean;
  readonly reason?: GeneratedReason;
  /** When known, the source file Schema *should* look at
   *  instead (e.g., `.proto` for a `.pb.go`). */
  readonly sourceFile?: string;
  /** Free-form detail surfaced in logs + caching.stats (e.g.,
   *  the matched toolchain name, the binary's size in MB). */
  readonly detail?: string;
}

// ── Filename patterns (extension or suffix-based) ──────────

const GENERATED_PATTERNS: readonly RegExp[] = [
  /\.pb\.go$/,
  /\.pb\.ts$/,
  /\.pb\.js$/,
  /_pb2\.py$/,
  /_pb2_grpc\.py$/,
  /_grpc\.pb\.go$/,
  /zz_generated_\w+\.go$/,
  /_string\.go$/,
  /\.generated\.\w+$/,
  /\.g\.dart$/,
  /\.freezed\.dart$/,
];

const GENERATED_DIRS: readonly string[] = [
  "__generated__",
  "generated",
  ".generated",
  "gen",
];

// ── Header comments — 10 first-line markers per Step 4 ─────
//
// Each marker is tested against the first 500 bytes of file
// content. Order matters only for matching speed (most-common
// first). Sourced from the canonical generators each language
// emits (Go go:generate, protoc, OpenAPI Generator, Prisma,
// SQLBoiler, Jooq, Quicktype, TypeScript build:tools).

const GENERATED_HEADERS: readonly { re: RegExp; toolchain: string }[] = [
  // 1. Go's stdlib generator marker — `code generated ... DO NOT EDIT`
  { re: /^\/\/ Code generated .+ DO NOT EDIT\.?$/m, toolchain: "go-generate" },
  // 2. Python "Generated by" (covers grpc-tools, protoc Python, datamodel-code-generator)
  { re: /^# Generated by /m, toolchain: "python-generator" },
  // 3. Generic AUTO-GENERATED marker (covers many codegens)
  { re: /^\/\/ AUTO-GENERATED/m, toolchain: "generic" },
  // 4. "This file is generated" (Stripe SDKs, Sentry SDKs, …)
  { re: /^\/\/ This file is generated/mi, toolchain: "generic" },
  // 5. ESLint-disable + @generated (TypeScript build tools, Relay)
  { re: /^\/\*\s*eslint-disable\s*\*\/\s*\n\/\/ @generated/m, toolchain: "ts-codegen" },
  // 6. Bare `@generated` JSDoc tag (Relay, GraphQL Codegen)
  { re: /^\/\*\s*@generated/m, toolchain: "graphql-codegen" },
  // 7. Hash-prefixed DO NOT EDIT (Python, Ruby, shell)
  { re: /^#\s*DO NOT EDIT/mi, toolchain: "generic" },
  // 8. Dart auto-generated marker (build_runner, freezed)
  { re: /^\/\/ GENERATED CODE - DO NOT MODIFY BY HAND/m, toolchain: "dart-build_runner" },
  // 9. SQL DDL "WARNING: DO NOT MODIFY" (sqlc, sqlboiler, prisma migrations)
  { re: /^--\s*Code generated.* DO NOT EDIT/mi, toolchain: "sql-codegen" },
  // 10. XML-ish header (Java JAXB, Quarkus, JaxRS clients)
  { re: /^<!--\s*Generated by/mi, toolchain: "java-codegen" },
];

// ── Codegen-toolchain detectors (filename + path heuristics) ──

/** Each entry: a pattern that fires on filenames produced by a
 *  specific codegen toolchain, plus the toolchain name and the
 *  inferred source file (when one can be derived). Reading order
 *  matches the Step 4 plan's list of 8 toolchains.
 *
 *  These supplement (not replace) GENERATED_PATTERNS — they're
 *  the more specific, named cases that warrant their own filter
 *  category in `caching.stats`. */
interface ToolchainPattern {
  readonly toolchain: string;
  readonly test: (path: string) => boolean;
  readonly sourceFile?: (path: string) => string | undefined;
}

const CODEGEN_TOOLCHAINS: readonly ToolchainPattern[] = [
  // 1. protoc — Google's protobuf compiler. Many language
  //    suffixes; the GENERATED_PATTERNS above catch most.
  //    This entry catches Java + C++ + Ruby + PHP + Rust
  //    variants not in the base set.
  {
    toolchain: "protoc",
    test: (p) =>
      /OuterClass\.java$/.test(p) ||
      /\.pb\.cc$/.test(p) ||
      /\.pb\.h$/.test(p) ||
      /_pb\.rb$/.test(p) ||
      /\.pb\.rs$/.test(p) ||
      /_pb_grpc\.rb$/.test(p),
  },
  // 2. swagger-codegen — produces files with a "swagger" hint
  //    in their path; also commonly in `swagger-client/` dirs.
  {
    toolchain: "swagger-codegen",
    test: (p) =>
      /\/swagger-client\//.test(p) ||
      /SwaggerClient/.test(p) ||
      /-swagger-generated\./.test(p),
  },
  // 3. openapi-generator — replaces swagger-codegen; emits
  //    files in `openapi/` or `generated-sources/openapi/`.
  {
    toolchain: "openapi-generator",
    test: (p) =>
      /\/generated-sources\/openapi\//.test(p) ||
      /\/openapi\/generated\//.test(p) ||
      /\.openapi\.gen\.\w+$/.test(p),
  },
  // 4. prisma — emits TS files under node_modules/.prisma/ +
  //    a `prisma/migrations/` SQL dir + the generated client
  //    at `node_modules/@prisma/client/`.
  {
    toolchain: "prisma",
    test: (p) =>
      /\/\.prisma\//.test(p) ||
      /\/@prisma\/client\//.test(p) ||
      /\/prisma\/migrations\/.+\.sql$/.test(p),
  },
  // 5. sqlc — generates Go from SQL. Convention: files named
  //    `*.sql.go`, often in a `db/` or `internal/db/` dir.
  {
    toolchain: "sqlc",
    test: (p) => /\.sql\.go$/.test(p),
    sourceFile: (p) => p.replace(/\.sql\.go$/, ".sql"),
  },
  // 6. sqlboiler — generates Go models from a DB schema.
  //    Convention: `_test_main.go`-style suffixes or files
  //    under `models/` with a `boil_` prefix.
  {
    toolchain: "sqlboiler",
    test: (p) => /\/boil_\w+\.go$/.test(p) || /\/models\/.+\.boilerplate\.go$/.test(p),
  },
  // 7. datamodel-code-generator — Python; emits Pydantic
  //    models with a "auto-generated by datamodel-codegen"
  //    header (caught by header rule too) and conventional
  //    `pydantic_models/` paths.
  {
    toolchain: "datamodel-code-generator",
    test: (p) => /\/pydantic_models\/.+\.py$/.test(p),
  },
  // 8. oapi-codegen — Go OpenAPI codegen. Convention: files
  //    named `*.gen.go` in a top-level package.
  {
    toolchain: "oapi-codegen",
    test: (p) => /\.gen\.go$/.test(p),
  },
];

// ── Binary blob detection ──────────────────────────────────
//
// A file is treated as binary when (a) its first KB contains a
// NULL byte (the canonical Git heuristic) OR (b) it's > 1 MB
// AND its first 256 bytes aren't valid UTF-8. The size + null
// check is from `git diff`'s `is_binary` and the file(1) command.
// Per Step 4: "size > 1 MB + non-text first 1 KB". We tighten
// to "size > 1 MB OR null-byte" so we also catch small images
// + compiled stubs.

const BINARY_SIZE_BYTES = 1 * 1024 * 1024;

export function isBinaryContent(content: string, byteLength?: number): boolean {
  // Big files where the first KB has no readable ASCII / UTF-8
  // are almost always binary — the looksLikeBinary heuristic
  // catches images, PDFs, compiled stubs.
  if (byteLength !== undefined && byteLength > BINARY_SIZE_BYTES) {
    return looksLikeBinary(content.slice(0, 1024));
  }
  // For smaller files: first check for a literal NUL byte (the
  // canonical Git heuristic). If absent but the first KB looks
  // non-textual (high control-byte density), still flag as
  // binary — catches embedded blobs that don't happen to have
  // a NUL in the first KB.
  if (content.length === 0) return false;
  const head = content.slice(0, 1024);
  if (head.includes("\u0000")) return true;
  return looksLikeBinary(head);
}

function looksLikeBinary(head: string): boolean {
  if (head.length === 0) return false;
  if (head.includes("\u0000")) return true;
  // Count non-printable, non-whitespace chars. Pure text rarely
  // exceeds 5%; binary blobs (PDFs, images, compiled artefacts)
  // are much higher.
  let nonPrintable = 0;
  for (let i = 0; i < head.length; i++) {
    const c = head.charCodeAt(i);
    if (c < 9 || (c > 13 && c < 32)) nonPrintable++;
  }
  return nonPrintable / head.length > 0.3;
}

// ── Main detector ──────────────────────────────────────────

export function isGeneratedFile(filePath: string, contentHead?: string): GeneratedFileInfo {
  // 1. Filename-pattern (deterministic, cheapest).
  for (const pattern of GENERATED_PATTERNS) {
    if (pattern.test(filePath)) {
      const sourceFile = inferSourceFile(filePath);
      return sourceFile
        ? { isGenerated: true, reason: "filename-pattern", sourceFile }
        : { isGenerated: true, reason: "filename-pattern" };
    }
  }

  // 2. Codegen toolchain (named cases that get their own filter
  //    category). Checked BEFORE the generated-directory pass
  //    because some toolchain paths share segments with the
  //    generic `generated/` directory name (e.g.,
  //    `/openapi/generated/`); the specific toolchain match is
  //    more informative.
  for (const tc of CODEGEN_TOOLCHAINS) {
    if (tc.test(filePath)) {
      const sourceFile = tc.sourceFile?.(filePath);
      const base: GeneratedFileInfo = {
        isGenerated: true,
        reason: "codegen-toolchain",
        detail: tc.toolchain,
      };
      return sourceFile ? { ...base, sourceFile } : base;
    }
  }

  // 3. Generated directory (per-segment check).
  const parts = filePath.split("/");
  for (const dir of GENERATED_DIRS) {
    if (parts.includes(dir)) {
      return { isGenerated: true, reason: "generated-directory" };
    }
  }

  // 4. Header comment in the first 500 bytes.
  if (contentHead) {
    const head = contentHead.slice(0, 500);
    for (const { re, toolchain } of GENERATED_HEADERS) {
      if (re.test(head)) {
        return { isGenerated: true, reason: "header-comment", detail: toolchain };
      }
    }

    // 5. Binary blob — last check because it's the most
    //    expensive scan. Only run when content is available.
    if (isBinaryContent(contentHead)) {
      return { isGenerated: true, reason: "binary-blob" };
    }
  }

  return { isGenerated: false };
}

function inferSourceFile(filePath: string): string | undefined {
  if (filePath.endsWith(".pb.go") || filePath.endsWith(".pb.ts") || filePath.endsWith(".pb.js")) {
    return filePath.replace(/\.pb\.\w+$/, ".proto");
  }
  if (filePath.endsWith("_pb2.py") || filePath.endsWith("_pb2_grpc.py")) {
    return filePath.replace(/_pb2(?:_grpc)?\.py$/, ".proto");
  }
  return undefined;
}
