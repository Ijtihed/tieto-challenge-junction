// Per architecture/schema-v3.md §3.8 — AGENTS.md round-trip writer.
// Reads AGENTS.md (or CLAUDE.md / .cursor/rules), finds the Schema-fenced
// section, and writes graph-derived facts into it. Idempotent:
// user-edited text outside the fence is never touched.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import type { MultiRepoGraph } from "../../domain/multi-repo.ts";
import type { Violation } from "../../domain/types.ts";
import { NODE_KINDS } from "../../domain/vocabulary.ts";

const FENCE_START = "<!-- schema:facts:start -->";
const FENCE_END = "<!-- schema:facts:end -->";
const FENCE_ID = "schema-facts-v1";

export type AgentsMdResult = {
  writtenPath: string;
  fenceId: string;
  schemaSection: string;
} & ({ userSection: string } | { userSection?: never });

export function readAgentsMd(
  rootPath: string,
  opts?: { includeUserSection?: boolean },
): AgentsMdResult | null {
  const candidates = ["AGENTS.md", "CLAUDE.md"];
  let filePath: string | null = null;
  let content = "";

  for (const name of candidates) {
    const p = resolve(rootPath, name);
    if (existsSync(p)) {
      filePath = p;
      content = readFileSync(p, "utf-8");
      break;
    }
  }

  if (!filePath) {
    const base = { writtenPath: resolve(rootPath, "AGENTS.md"), fenceId: FENCE_ID, schemaSection: "" };
    return opts?.includeUserSection ? { ...base, userSection: "" } : base;
  }

  const startIdx = content.indexOf(FENCE_START);
  const endIdx = content.indexOf(FENCE_END);

  let schemaSection = "";
  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    schemaSection = content.slice(startIdx + FENCE_START.length, endIdx).trim();
  }

  const base = { writtenPath: filePath, fenceId: FENCE_ID, schemaSection };

  if (opts?.includeUserSection) {
    let userSection: string;
    if (startIdx !== -1 && endIdx !== -1) {
      userSection = (content.slice(0, startIdx) + content.slice(endIdx + FENCE_END.length)).trim();
    } else {
      userSection = content.trim();
    }
    return { ...base, userSection };
  }

  return base;
}

export function renderFacts(graph: MultiRepoGraph, violations: Violation[]): string {
  const allNodes = graph.repos.flatMap((r) => r.nodes);
  const allEdges = graph.repos.flatMap((r) => r.edges);

  const languages = [...new Set(allNodes.flatMap((n) => {
    const ext = n.filePath?.split(".").pop();
    const map: Record<string, string> = { ts: "TypeScript", py: "Python", go: "Go", java: "Java", kt: "Kotlin", rb: "Ruby", rs: "Rust" };
    return ext && map[ext] ? [map[ext]!] : [];
  }))];

  const kindCounts: Record<string, number> = {};
  for (const n of allNodes) kindCounts[n.kind] = (kindCounts[n.kind] ?? 0) + 1;

  const relationCounts: Record<string, number> = {};
  for (const e of allEdges) relationCounts[e.relation] = (relationCounts[e.relation] ?? 0) + 1;

  const contracts = allNodes.filter((n) => n.kind === NODE_KINDS.contract);
  const handlers = allNodes.filter((n) => n.kind === NODE_KINDS.route_handler);

  const lines: string[] = [
    "## Schema-derived architectural facts",
    "",
    `> Auto-generated by Schema. Do not edit inside the fence.`,
    `> Last updated: ${new Date().toISOString().slice(0, 10)}`,
    "",
    `**Languages:** ${languages.join(", ") || "none detected"}`,
    `**Nodes:** ${allNodes.length} · **Edges:** ${allEdges.length}`,
    "",
  ];

  if (Object.keys(kindCounts).length > 0) {
    lines.push("### Node breakdown", "");
    for (const [kind, count] of Object.entries(kindCounts).sort((a, b) => b[1] - a[1])) {
      lines.push(`- ${kind}: ${count}`);
    }
    lines.push("");
  }

  if (Object.keys(relationCounts).length > 0) {
    lines.push("### Edge breakdown", "");
    for (const [rel, count] of Object.entries(relationCounts).sort((a, b) => b[1] - a[1])) {
      lines.push(`- ${rel}: ${count}`);
    }
    lines.push("");
  }

  if (handlers.length > 0) {
    lines.push(`### Route handlers (${handlers.length})`, "");
    for (const h of handlers.slice(0, 20)) {
      lines.push(`- \`${h.name}\` (${h.filePath?.split("/").pop() ?? "unknown"})`);
    }
    if (handlers.length > 20) lines.push(`- ... and ${handlers.length - 20} more`);
    lines.push("");
  }

  if (contracts.length > 0) {
    lines.push(`### Cross-language contracts (${contracts.length})`, "");
    for (const c of contracts.slice(0, 20)) {
      lines.push(`- \`${c.name}\``);
    }
    lines.push("");
  }

  if (violations.length > 0) {
    lines.push(`### Active violations (${violations.length})`, "");
    for (const v of violations.slice(0, 10)) {
      const icon = v.severity === "error" ? "❌" : v.severity === "warn" ? "⚠️" : "ℹ️";
      lines.push(`- ${icon} **${v.ruleId}**: ${v.message}`);
    }
    if (violations.length > 10) lines.push(`- ... and ${violations.length - 10} more`);
    lines.push("");
  }

  return lines.join("\n");
}

export function writeFacts(
  rootPath: string,
  facts: string,
  target: string = "AGENTS.md",
): { writtenPath: string; charsAdded: number; charsRemoved: number; fenceId: string } {
  const filePath = resolve(rootPath, target);
  let content = "";
  let existingFenceChars = 0;

  if (existsSync(filePath)) {
    content = readFileSync(filePath, "utf-8");
    const startIdx = content.indexOf(FENCE_START);
    const endIdx = content.indexOf(FENCE_END);
    if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
      existingFenceChars = endIdx + FENCE_END.length - startIdx;
      content = content.slice(0, startIdx) + content.slice(endIdx + FENCE_END.length);
    }
  }

  const fencedBlock = `${FENCE_START}\n${facts}\n${FENCE_END}`;
  const newContent = content.trim()
    ? content.trimEnd() + "\n\n" + fencedBlock + "\n"
    : fencedBlock + "\n";

  writeFileSync(filePath, newContent, "utf-8");

  return {
    writtenPath: filePath,
    charsAdded: fencedBlock.length,
    charsRemoved: existingFenceChars,
    fenceId: FENCE_ID,
  };
}
