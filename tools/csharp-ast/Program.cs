namespace CSharpAst;

// Roslyn-backed C# analysis for Schema.
//   csharp-ast graph <root>                        -> symbol graph (nodes + edges) as JSON
//   csharp-ast diff  <root> <baseRef> <headRef>    -> member-level AST diff between two git refs
public static class Program
{
    private static readonly JsonSerializerOptions Json = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
    };

    public static int Main(string[] args)
    {
        try
        {
            object result = args switch
            {
                ["graph", var root, ..] => GraphBuilder.Build(Path.GetFullPath(root)),
                ["diff", var root, var baseRef, var headRef] => AstDiff.Run(Path.GetFullPath(root), baseRef, headRef),
                _ => throw new ArgumentException("usage: csharp-ast graph <root> | csharp-ast diff <root> <baseRef> <headRef>"),
            };
            using var stdout = Console.OpenStandardOutput();
            JsonSerializer.Serialize(stdout, result, result.GetType(), Json);
            return 0;
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine(ex.ToString());
            return 1;
        }
    }
}

public sealed record MemberInfo(
    string Key,
    string Name,
    string CsKind,
    string File,
    int StartLine,
    int EndLine,
    string Accessibility,
    bool PublicApi,
    string[] Attributes,
    string Signature,
    string HeaderTokens,
    string BodyTokens,
    string AttributeTokens,
    bool IsTest,
    string? ContainingTypeKey,
    [property: JsonIgnore] SyntaxNode Syntax)
{
    public uint Fingerprint => Hash.Fnv32(HeaderTokens + "\u0001" + BodyTokens);
}

public static class Hash
{
    public static uint Fnv32(string s)
    {
        uint h = 2166136261;
        foreach (char c in s)
        {
            h ^= c;
            h *= 16777619;
        }
        return h;
    }
}

public static class Members
{
    private static readonly HashSet<string> TestAttributes = new(StringComparer.Ordinal)
    {
        "Fact", "Theory", "Test", "TestMethod", "TestCase", "SkippableFact", "SkippableTheory",
    };

    public static bool IsGeneratedPath(string path, string text) =>
        path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
        || path.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase)
        || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
        || text.AsSpan(0, Math.Min(text.Length, 600)).Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);

    public static bool IsTestPath(string path) =>
        path.Replace('\\', '/').Split('/').Any(seg =>
            seg.Equals("tests", StringComparison.OrdinalIgnoreCase)
            || seg.Equals("test", StringComparison.OrdinalIgnoreCase)
            || seg.EndsWith(".Tests", StringComparison.OrdinalIgnoreCase)
            || seg.EndsWith("Tests", StringComparison.Ordinal));

    public static string Tokens(SyntaxNode? node) =>
        node is null ? "" : string.Join(" ", node.DescendantTokens().Select(t => t.Text));

    private static string TokensBefore(SyntaxNode node, int position) =>
        string.Join(" ", node.DescendantTokens().Where(t => t.SpanStart < position && !IsInAttributeList(t)).Select(t => t.Text));

    private static bool IsInAttributeList(SyntaxToken t) => t.Parent?.AncestorsAndSelf().Any(a => a is AttributeListSyntax) == true;

    public static List<MemberInfo> Collect(SyntaxTree tree, string relPath)
    {
        var list = new List<MemberInfo>();
        var root = tree.GetRoot();
        bool fileIsTest = IsTestPath(relPath);
        foreach (var type in root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
        {
            var typeKey = TypeKey(type);
            bool typePublic = IsTypePublic(type);
            var typeAttrs = AttributeNames(type.AttributeLists);
            list.Add(Make(typeKey, type.Identifier.Text, TypeKind(type), relPath, type,
                Access(type.Modifiers, defaultAccess: type.Parent is BaseTypeDeclarationSyntax ? "private" : "internal"),
                typePublic, typeAttrs,
                header: TokensBefore(type, type.OpenBraceToken.IsKind(SyntaxKind.None) ? type.Span.End : type.OpenBraceToken.SpanStart),
                body: "",
                attrTokens: string.Join(" ", type.AttributeLists.Select(Tokens)),
                isTest: fileIsTest, containing: type.Parent is BaseTypeDeclarationSyntax p ? TypeKey(p) : null));

            if (type is not TypeDeclarationSyntax td)
            {
                continue;
            }

            bool isInterface = td is InterfaceDeclarationSyntax;
            foreach (var m in td.Members)
            {
                if (m is BaseTypeDeclarationSyntax)
                {
                    continue;
                }

                var attrs = AttributeNames(m.AttributeLists);
                bool isTest = fileIsTest || attrs.Any(TestAttributes.Contains);
                string access = Access(m.Modifiers, isInterface ? "public" : "private");
                bool publicApi = typePublic && (access is "public" or "protected" or "protected internal");
                string attrTokens = string.Join(" ", m.AttributeLists.Select(Tokens));

                switch (m)
                {
                    case BaseMethodDeclarationSyntax method:
                    {
                        SyntaxNode? body = (SyntaxNode?)method.Body ?? method.ExpressionBody;
                        string name = method switch
                        {
                            MethodDeclarationSyntax md => md.Identifier.Text,
                            ConstructorDeclarationSyntax => ".ctor",
                            DestructorDeclarationSyntax => ".dtor",
                            OperatorDeclarationSyntax od => "op_" + od.OperatorToken.Text,
                            ConversionOperatorDeclarationSyntax co => "op_" + co.ImplicitOrExplicitKeyword.Text + "_" + Tokens(co.Type),
                            _ => "method",
                        };
                        string paramSig = string.Join(",", method.ParameterList.Parameters.Select(p => Tokens(p.Type).Replace(" ", "")));
                        string typeParams = method is MethodDeclarationSyntax { TypeParameterList: { } tpl } ? "`" + tpl.Parameters.Count : "";
                        string kind = method is ConstructorDeclarationSyntax ? "constructor" : "method";
                        list.Add(Make($"{typeKey}.{name}{typeParams}({paramSig})", name, kind, relPath, method, access, publicApi, attrs,
                            header: TokensBefore(method, body?.SpanStart ?? method.Span.End),
                            body: Tokens(body), attrTokens, isTest, typeKey));
                        break;
                    }

                    case BasePropertyDeclarationSyntax prop:
                    {
                        string name = prop switch
                        {
                            PropertyDeclarationSyntax pd => pd.Identifier.Text,
                            EventDeclarationSyntax ed => ed.Identifier.Text,
                            IndexerDeclarationSyntax => "this[]",
                            _ => "property",
                        };
                        SyntaxNode? body = (SyntaxNode?)prop.AccessorList ?? (prop as PropertyDeclarationSyntax)?.ExpressionBody;
                        list.Add(Make($"{typeKey}.{name}", name, prop is EventDeclarationSyntax ? "event" : "property", relPath, prop, access, publicApi, attrs,
                            header: TokensBefore(prop, body?.SpanStart ?? prop.Span.End),
                            body: Tokens(body) + " " + Tokens((prop as PropertyDeclarationSyntax)?.Initializer), attrTokens, isTest, typeKey));
                        break;
                    }

                    case BaseFieldDeclarationSyntax field:
                        foreach (var v in field.Declaration.Variables)
                        {
                            list.Add(Make($"{typeKey}.{v.Identifier.Text}", v.Identifier.Text, "field", relPath, field, access, publicApi, attrs,
                                header: Tokens(field.Declaration.Type) + " " + string.Join(" ", field.Modifiers.Select(t => t.Text)) + " " + v.Identifier.Text,
                                body: Tokens(v.Initializer), attrTokens, isTest, typeKey));
                        }

                        break;

                    case DelegateDeclarationSyntax del:
                        list.Add(Make($"{typeKey}.{del.Identifier.Text}", del.Identifier.Text, "delegate", relPath, del, access, publicApi, attrs,
                            header: Tokens(del), body: "", attrTokens, isTest, typeKey));
                        break;
                }
            }
        }

        return list;
    }

    private static MemberInfo Make(string key, string name, string csKind, string file, SyntaxNode node, string access, bool publicApi,
        string[] attrs, string header, string body, string attrTokens, bool isTest, string? containing)
    {
        var span = node.GetLocation().GetLineSpan();
        string sig = SourceSignature(node);
        return new MemberInfo(key, name, csKind, file, span.StartLinePosition.Line + 1, span.EndLinePosition.Line + 1,
            access, publicApi, attrs, sig, header, body, attrTokens, isTest, containing, node);
    }

    /// <summary>Declaration text from after the attributes up to the body, whitespace collapsed.</summary>
    private static string SourceSignature(SyntaxNode node)
    {
        var first = node.ChildNodesAndTokens().FirstOrDefault(c => !c.IsKind(SyntaxKind.AttributeList));
        int start = first.IsToken ? first.AsToken().SpanStart : first.AsNode()?.SpanStart ?? node.SpanStart;
        int end = node switch
        {
            BaseMethodDeclarationSyntax m => ((SyntaxNode?)m.Body ?? m.ExpressionBody)?.SpanStart ?? m.Span.End,
            BasePropertyDeclarationSyntax p => ((SyntaxNode?)p.AccessorList ?? (p as PropertyDeclarationSyntax)?.ExpressionBody)?.SpanStart ?? p.Span.End,
            BaseTypeDeclarationSyntax t => t.OpenBraceToken.IsKind(SyntaxKind.None) ? t.Span.End : t.OpenBraceToken.SpanStart,
            _ => node.Span.End,
        };
        string text = node.SyntaxTree.GetText().ToString(Microsoft.CodeAnalysis.Text.TextSpan.FromBounds(start, Math.Max(start, end)));
        return System.Text.RegularExpressions.Regex.Replace(text, @"\s+", " ").Trim().TrimEnd(';');
    }

    public static string TypeKey(BaseTypeDeclarationSyntax type)
    {
        var parts = new List<string>();
        SyntaxNode? cur = type;
        while (cur is not null)
        {
            switch (cur)
            {
                case BaseTypeDeclarationSyntax t:
                    string arity = t is TypeDeclarationSyntax { TypeParameterList: { } tpl } ? "`" + tpl.Parameters.Count : "";
                    parts.Add(t.Identifier.Text + arity);
                    break;
                case BaseNamespaceDeclarationSyntax ns:
                    parts.Add(ns.Name.ToString());
                    break;
            }

            cur = cur.Parent;
        }

        parts.Reverse();
        return string.Join(".", parts);
    }

    private static string TypeKind(BaseTypeDeclarationSyntax t) => t switch
    {
        InterfaceDeclarationSyntax => "interface",
        RecordDeclarationSyntax r => r.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) ? "record struct" : "record",
        StructDeclarationSyntax => "struct",
        EnumDeclarationSyntax => "enum",
        _ => "class",
    };

    private static bool IsTypePublic(BaseTypeDeclarationSyntax type)
    {
        SyntaxNode? cur = type;
        while (cur is BaseTypeDeclarationSyntax t)
        {
            string a = Access(t.Modifiers, t.Parent is BaseTypeDeclarationSyntax ? "private" : "internal");
            if (a is not ("public" or "protected" or "protected internal"))
            {
                return false;
            }

            cur = t.Parent;
        }

        return true;
    }

    public static string Access(SyntaxTokenList mods, string defaultAccess)
    {
        bool has(SyntaxKind k) => mods.Any(m => m.IsKind(k));
        if (has(SyntaxKind.PublicKeyword)) return "public";
        if (has(SyntaxKind.ProtectedKeyword) && has(SyntaxKind.InternalKeyword)) return "protected internal";
        if (has(SyntaxKind.PrivateKeyword) && has(SyntaxKind.ProtectedKeyword)) return "private protected";
        if (has(SyntaxKind.ProtectedKeyword)) return "protected";
        if (has(SyntaxKind.InternalKeyword)) return "internal";
        if (has(SyntaxKind.PrivateKeyword)) return "private";
        return defaultAccess;
    }

    private static string[] AttributeNames(SyntaxList<AttributeListSyntax> lists) =>
        lists.SelectMany(l => l.Attributes)
            .Select(a => a.Name.ToString().Split('.').Last())
            .Select(n => n.EndsWith("Attribute", StringComparison.Ordinal) ? n[..^"Attribute".Length] : n)
            .ToArray();
}

public static class GraphBuilder
{
    private static readonly string[] SkipDirs = ["/bin/", "/obj/", "/.git/", "/node_modules/", "/packages/"];

    public sealed record Node(string Key, string Name, string CsKind, string Kind, string File, int StartLine, int EndLine,
        string Accessibility, bool PublicApi, string[] Attributes, string Signature, uint Fingerprint, bool Generated, bool IsTest);

    public sealed record Edge(string Source, string Target, string Relation, bool Resolved);

    public sealed record Result(List<string> Files, List<Node> Nodes, List<Edge> Edges, Dictionary<string, int> Stats);

    public static Result Build(string root)
    {
        var files = Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories)
            .Where(f => !SkipDirs.Any(d => f.Replace('\\', '/').Contains(d)))
            .OrderBy(f => f, StringComparer.Ordinal)
            .ToList();

        var parse = new CSharpParseOptions(LanguageVersion.Preview);
        var trees = new List<(SyntaxTree Tree, string Rel, bool Generated)>();
        foreach (var f in files)
        {
            string text = File.ReadAllText(f);
            string rel = Path.GetRelativePath(root, f).Replace('\\', '/');
            trees.Add((CSharpSyntaxTree.ParseText(text, parse, path: rel), rel, Members.IsGeneratedPath(rel, text)));
        }

        var refs = ((string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ?? "")
            .Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries)
            .Where(p => p.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
            .Select(p => MetadataReference.CreateFromFile(p));
        var compilation = CSharpCompilation.Create("schema-csharp-graph", trees.Select(t => t.Tree), refs,
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, allowUnsafe: true));

        var nodes = new List<Node>();
        var byKey = new Dictionary<string, MemberInfo>(StringComparer.Ordinal);
        var symbolToKey = new Dictionary<ISymbol, string>(SymbolEqualityComparer.Default);
        var keysByName = new Dictionary<string, List<string>>(StringComparer.Ordinal);
        var edges = new HashSet<Edge>();
        int unresolved = 0;

        foreach (var (tree, rel, generated) in trees)
        {
            var model = compilation.GetSemanticModel(tree);
            string fileKey = "file:" + rel;
            nodes.Add(new Node(fileKey, Path.GetFileName(rel), "file", Members.IsTestPath(rel) ? "test" : "utility", rel, 1,
                tree.GetLineSpan(tree.GetRoot().FullSpan).EndLinePosition.Line + 1, "public", false, [], rel, 0, generated, Members.IsTestPath(rel)));

            foreach (var m in Members.Collect(tree, rel))
            {
                if (!byKey.TryAdd(m.Key, m))
                {
                    continue;
                }

                nodes.Add(new Node(m.Key, m.Name, m.CsKind, KindFor(m), rel, m.StartLine, m.EndLine, m.Accessibility, m.PublicApi,
                    m.Attributes, m.Signature, m.Fingerprint, generated, m.IsTest));
                edges.Add(new Edge(m.ContainingTypeKey ?? fileKey, m.Key, "declares", true));
                if (!keysByName.TryGetValue(m.Name, out var named))
                {
                    keysByName[m.Name] = named = [];
                }

                named.Add(m.Key);

                SyntaxNode declNode = m.Syntax is BaseFieldDeclarationSyntax fd
                    ? fd.Declaration.Variables.First(v => v.Identifier.Text == m.Name)
                    : m.Syntax;
                var sym = model.GetDeclaredSymbol(declNode);
                if (sym is not null)
                {
                    symbolToKey.TryAdd(sym.OriginalDefinition, m.Key);
                }
            }
        }

        foreach (var (tree, rel, _) in trees)
        {
            var model = compilation.GetSemanticModel(tree);
            foreach (var m in Members.Collect(tree, rel))
            {
                if (!byKey.TryGetValue(m.Key, out var owner) || owner.File != rel)
                {
                    continue;
                }

                if (m.Syntax is BaseMethodDeclarationSyntax && model.GetDeclaredSymbol(m.Syntax) is IMethodSymbol ms && m.ContainingTypeKey is { } ownerType
                    && (ms.IsOverride || ms.ExplicitInterfaceImplementations.Length > 0 || ImplementsInterfaceMember(ms)))
                {
                    edges.Add(new Edge(ownerType, m.Key, "dispatch", true));
                }

                if (m.Syntax is BaseTypeDeclarationSyntax typeDecl)
                {
                    foreach (var bt in typeDecl.BaseList?.Types ?? default)
                    {
                        var t = model.GetTypeInfo(bt.Type).Type?.OriginalDefinition;
                        if (t is not null && symbolToKey.TryGetValue(t, out var target))
                        {
                            edges.Add(new Edge(m.Key, target, t.TypeKind == TypeKind.Interface ? "implements" : "extends", true));
                        }
                    }

                    continue;
                }

                foreach (var expr in m.Syntax.DescendantNodes())
                {
                    if (expr is not (InvocationExpressionSyntax or BaseObjectCreationExpressionSyntax or MemberAccessExpressionSyntax or IdentifierNameSyntax))
                    {
                        continue;
                    }

                    if (expr is IdentifierNameSyntax { Parent: MemberAccessExpressionSyntax or InvocationExpressionSyntax })
                    {
                        continue;
                    }

                    var info = model.GetSymbolInfo(expr);
                    var sym = (info.Symbol ?? info.CandidateSymbols.FirstOrDefault())?.OriginalDefinition;
                    if (sym is IMethodSymbol { ReducedFrom: { } reduced })
                    {
                        sym = reduced.OriginalDefinition;
                    }

                    var full = info.Symbol ?? info.CandidateSymbols.FirstOrDefault();
                    foreach (var ta in TypeArguments(full))
                    {
                        if (symbolToKey.TryGetValue(ta, out var taKey) && taKey != m.Key)
                        {
                            edges.Add(new Edge(m.Key, taKey, "references_type", true));
                        }
                    }

                    if (sym is not null && symbolToKey.TryGetValue(sym, out var target))
                    {
                        if (target != m.Key)
                        {
                            string rel2 = sym is IMethodSymbol ? "calls" : sym is ITypeSymbol ? "references_type" : "reads_field";
                            edges.Add(new Edge(m.Key, target, rel2, info.Symbol is not null));
                        }
                    }
                    else if (sym is null && expr is InvocationExpressionSyntax inv)
                    {
                        string? name = inv.Expression switch
                        {
                            MemberAccessExpressionSyntax ma => ma.Name.Identifier.Text,
                            IdentifierNameSyntax id => id.Identifier.Text,
                            GenericNameSyntax gn => gn.Identifier.Text,
                            _ => null,
                        };
                        if (name is not null && keysByName.TryGetValue(name, out var cands) && cands.Count == 1 && cands[0] != m.Key)
                        {
                            edges.Add(new Edge(m.Key, cands[0], "calls", false));
                            unresolved++;
                        }
                    }
                }
            }
        }

        return new Result(trees.Select(t => t.Rel).ToList(), nodes, edges.ToList(), new Dictionary<string, int>
        {
            ["files"] = trees.Count,
            ["nodes"] = nodes.Count,
            ["edges"] = edges.Count,
            ["nameResolvedEdges"] = unresolved,
        });
    }

    private static IEnumerable<ISymbol> TypeArguments(ISymbol? s)
    {
        var seen = new HashSet<ISymbol>(SymbolEqualityComparer.Default);
        void Walk(ITypeSymbol? t)
        {
            for (var cur = t as INamedTypeSymbol; cur is not null; cur = cur.ContainingType)
            {
                foreach (var a in cur.TypeArguments)
                {
                    if (a is INamedTypeSymbol na && seen.Add(na.OriginalDefinition))
                    {
                        Walk(na);
                    }
                }
            }
        }

        switch (s)
        {
            case ITypeSymbol t: Walk(t); break;
            case IMethodSymbol m:
                Walk(m.ContainingType);
                foreach (var a in m.TypeArguments.OfType<INamedTypeSymbol>()) { if (seen.Add(a.OriginalDefinition)) Walk(a); }
                break;
            case { ContainingType: { } ct }: Walk(ct); break;
        }

        return seen;
    }

    private static bool ImplementsInterfaceMember(IMethodSymbol m) =>
        m.ContainingType.AllInterfaces.SelectMany(i => i.GetMembers().OfType<IMethodSymbol>())
            .Any(im => SymbolEqualityComparer.Default.Equals(m.ContainingType.FindImplementationForInterfaceMember(im), m));

    private static string KindFor(MemberInfo m) => m switch
    {
        { IsTest: true } => "test",
        { CsKind: "interface" } => "contract",
        { CsKind: "record" or "record struct" or "struct" or "enum" } => "model",
        { CsKind: "class" } => "service",
        _ => "utility",
    };
}

public static class AstDiff
{
    public sealed record Side(string Signature, string Accessibility, bool PublicApi, string[] Attributes, int StartLine, int EndLine, string Text);

    public sealed record MemberChange(string Key, string Name, string CsKind, string File, List<string> Changes, bool IsTest,
        bool PublicApiBefore, bool PublicApiAfter, Side? Before, Side? After);

    public sealed record FileChange(string Path, string Status, string? OldPath, bool IsCs, bool Generated, bool IsTest,
        int Added, int Deleted, bool TriviaOnly, List<string> FileLevel);

    public sealed record Result(string BaseRef, string HeadRef, string BaseSha, string HeadSha, List<FileChange> Files, List<MemberChange> Members);

    public static Result Run(string root, string baseRef, string headRef)
    {
        string baseSha = Git(root, "rev-parse", baseRef).Trim();
        string headSha = Git(root, "rev-parse", headRef).Trim();
        var numstat = Git(root, "diff", "--numstat", "-M", baseSha, headSha)
            .Split('\n', StringSplitOptions.RemoveEmptyEntries)
            .Select(l => l.Split('\t'))
            .Where(p => p.Length >= 3)
            .ToDictionary(p => NormalizeRenamePath(p[2]), p => (int.TryParse(p[0], out var a) ? a : 0, int.TryParse(p[1], out var d) ? d : 0));

        var files = new List<FileChange>();
        var changes = new List<MemberChange>();
        var parse = new CSharpParseOptions(LanguageVersion.Preview);

        foreach (var line in Git(root, "diff", "--name-status", "-M", baseSha, headSha).Split('\n', StringSplitOptions.RemoveEmptyEntries))
        {
            var parts = line.Split('\t');
            string status = parts[0][..1];
            string path = parts[^1];
            string? oldPath = status == "R" ? parts[1] : null;
            bool isCs = path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase);
            numstat.TryGetValue(path, out var ns);

            string before = status == "A" ? "" : GitShow(root, baseSha, oldPath ?? path);
            string after = status == "D" ? "" : GitShow(root, headSha, path);
            bool generated = Members.IsGeneratedPath(path, after.Length > 0 ? after : before);
            bool isTest = Members.IsTestPath(path);
            var fileLevel = new List<string>();
            bool triviaOnly = false;

            if (isCs)
            {
                var tb = CSharpSyntaxTree.ParseText(before, parse, path: path);
                var ta = CSharpSyntaxTree.ParseText(after, parse, path: path);
                triviaOnly = before != after && Members.Tokens(tb.GetRoot()) == Members.Tokens(ta.GetRoot());

                string usingsBefore = string.Join(";", tb.GetRoot().DescendantNodes().OfType<UsingDirectiveSyntax>().Select(u => u.ToString().Trim()));
                string usingsAfter = string.Join(";", ta.GetRoot().DescendantNodes().OfType<UsingDirectiveSyntax>().Select(u => u.ToString().Trim()));
                if (usingsBefore != usingsAfter)
                {
                    fileLevel.Add("usings");
                }

                var mb = Members.Collect(tb, path).GroupBy(m => m.Key).ToDictionary(g => g.Key, g => g.First());
                var ma = Members.Collect(ta, path).GroupBy(m => m.Key).ToDictionary(g => g.Key, g => g.First());
                foreach (var key in mb.Keys.Union(ma.Keys))
                {
                    mb.TryGetValue(key, out var b);
                    ma.TryGetValue(key, out var a);
                    var kinds = new List<string>();
                    if (b is null) kinds.Add("added");
                    else if (a is null) kinds.Add("removed");
                    else
                    {
                        if (b.Accessibility != a.Accessibility) kinds.Add("accessibility");
                        if (b.AttributeTokens != a.AttributeTokens) kinds.Add("attributes");
                        if (b.HeaderTokens != a.HeaderTokens && b.Accessibility == a.Accessibility) kinds.Add("signature");
                        if (b.BodyTokens != a.BodyTokens) kinds.Add("body");
                        if (kinds.Count == 0 && b.Syntax.ToFullString() != a.Syntax.ToFullString() && a.CsKind is not ("class" or "struct" or "interface" or "record" or "record struct" or "enum"))
                        {
                            kinds.Add("trivia-only");
                        }
                    }

                    if (kinds.Count == 0)
                    {
                        continue;
                    }

                    var any = a ?? b!;
                    changes.Add(new MemberChange(key, any.Name, any.CsKind, path, kinds, any.IsTest,
                        b?.PublicApi ?? false, a?.PublicApi ?? false, ToSide(b), ToSide(a)));
                }
            }

            files.Add(new FileChange(path, status, oldPath, isCs, generated, isTest, ns.Item1, ns.Item2, triviaOnly, fileLevel));
        }

        return new Result(baseRef, headRef, baseSha, headSha, files, changes);
    }

    private static Side? ToSide(MemberInfo? m)
    {
        if (m is null)
        {
            return null;
        }

        string text = m.CsKind is "class" or "struct" or "interface" or "record" or "record struct" or "enum"
            ? m.Signature
            : m.Syntax.ToFullString().Trim('\r', '\n');
        return new Side(m.Signature, m.Accessibility, m.PublicApi, m.Attributes, m.StartLine, m.EndLine, text);
    }

    private static string NormalizeRenamePath(string p)
    {
        // numstat renames look like "dir/{old => new}/file" or "old => new"
        int brace = p.IndexOf('{');
        if (brace >= 0 && p.Contains(" => "))
        {
            int close = p.IndexOf('}', brace);
            string inner = p[(brace + 1)..close];
            string after = inner[(inner.IndexOf(" => ", StringComparison.Ordinal) + 4)..];
            return (p[..brace] + after + p[(close + 1)..]).Replace("//", "/");
        }

        return p.Contains(" => ") ? p[(p.IndexOf(" => ", StringComparison.Ordinal) + 4)..] : p;
    }

    private static string GitShow(string root, string sha, string path)
    {
        try
        {
            return Git(root, "show", $"{sha}:{path}");
        }
        catch
        {
            return "";
        }
    }

    private static string Git(string root, params string[] args)
    {
        var psi = new ProcessStartInfo("git") { RedirectStandardOutput = true, RedirectStandardError = true, WorkingDirectory = root, StandardOutputEncoding = Encoding.UTF8 };
        foreach (var a in args)
        {
            psi.ArgumentList.Add(a);
        }

        using var p = Process.Start(psi)!;
        string stdout = p.StandardOutput.ReadToEnd();
        string stderr = p.StandardError.ReadToEnd();
        p.WaitForExit();
        if (p.ExitCode != 0)
        {
            throw new InvalidOperationException($"git {string.Join(' ', args)} failed: {stderr}");
        }

        return stdout;
    }
